#!/usr/bin/env python3
"""Run card: the facts of one training run, COMPUTED from its data files and flags — never typed by hand.

Why (2026-11-11): questions such as "does the model learn whole trajectories?" were answered from memory and were
wrong (cur15k keeps every step of only 0.7% of its episodes). Every training run gets a card before it is launched;
answers about a run come from its card.

    python3 run_card.py --data DIR --train-set cur15k_v2,awgen_v2a --contract v2a --img-w 720 \
        --recipe "1044 steps x 16, lr 1e-5, warmup 30, frozen embedding, grad-ckpt, micro 1" --out card.md
"""
import argparse
import collections
import json
import os


def card_stats(rows):
    """Facts about a list of compact rows (dicts)."""
    by_src = collections.Counter(r.get("source") or "androidcontrol" for r in rows)
    eps = collections.defaultdict(set)
    n_steps = {}
    for r in rows:
        ep = str(r["ep"]).split(":", 1)[1] if str(r["ep"]).startswith("done:") else r["ep"]  # build_exec_data
        ep = int(ep) if isinstance(ep, str) and ep.isdigit() else ep
        eps[ep].add(r["step"])
        if r.get("n_steps") is not None:
            n_steps[ep] = r["n_steps"]
    # full = every ACTION step of the episode is present (the final `status` screen may or may not be a row)
    full = sum(1 for e, s in eps.items() if e in n_steps and set(range(n_steps[e])) <= s)
    per_ep = collections.Counter(min(len(s), 6) for s in eps.values())
    hkey = "history_v3" if any("history_v3" in r for r in rows) else "history"  # the history the contract reads
    hist = collections.Counter(min(len(r.get(hkey) or []), 5) for r in rows)
    acts = collections.Counter((r.get("action") or {}).get("action_type") for r in rows)
    with_el = [r for r in rows if r.get("elements") is not None]
    sample_hist = next((r[hkey] for r in rows if len(r.get(hkey) or []) >= 3), [])
    sizes = collections.Counter((r.get("W"), r.get("H")) for r in rows)
    return {
        "rows": len(rows), "sources": dict(by_src), "episodes": len(eps),
        "episodes_with_every_step": full, "steps_kept_per_episode(6=6+)": dict(sorted(per_ep.items())),
        "history_len_per_row(5=5+)": dict(sorted(hist.items())), "history_example": sample_hist,
        "action_mix": dict(acts.most_common()), "rows_with_element_list": len(with_el),
        "screen_sizes": {f"{w}x{h}": n for (w, h), n in sizes.most_common(4)},
    }


def render(stats, a):
    pct = lambda n, d: "%.1f%%" % (100.0 * n / d) if d else "-"  # noqa: E731
    s = stats
    lines = [
        f"# Run card — {a.name}",
        "",
        f"Generated by `benchmarks/train/run_card.py` from `{a.train_set}` in the data directory. Do not edit by hand.",
        "",
        "## Model input / output",
        f"* contract `{a.contract}`; image width {a.img_w} px (one screenshot, the current screen)",
        "* state text: goal + previous actions (history renderer of the contract) + element list (contract rule)",
        "* outputs: see `docs/research/CONTRACT-v3-io.md` and `ac_common.CONTRACTS`",
        "",
        "## Recipe",
        f"* {a.recipe}",
        "",
        "## Data (computed)",
        f"* rows: **{s['rows']}** — by source: {s['sources']}",
        f"* episodes: {s['episodes']}; episodes with EVERY step present: **{s['episodes_with_every_step']}** "
        f"({pct(s['episodes_with_every_step'], s['episodes'])})",
        f"* steps kept per episode (6 = 6+): {s['steps_kept_per_episode(6=6+)']}",
        f"* history length per row (5 = 5+): {s['history_len_per_row(5=5+)']}",
        f"* history example: `{s['history_example']}`",
        f"* action mix: {s['action_mix']}",
        f"* rows with an element list: {s['rows_with_element_list']} ({pct(s['rows_with_element_list'], s['rows'])})",
        f"* screen sizes (top): {s['screen_sizes']}",
        "",
        "## What this run is NOT (read before answering questions about it)",
        f"* whole trajectories: {s['episodes_with_every_step']} of {s['episodes']} episodes have every step "
        f"({pct(s['episodes_with_every_step'], s['episodes'])}); rows of source `aw_generator` are single first "
        "steps by design",
        "* trained on task success: no (imitation of single next actions only)",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--train-set", required=True)
    ap.add_argument("--contract", required=True)
    ap.add_argument("--img-w", type=int, required=True)
    ap.add_argument("--recipe", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rows = []
    for name in a.train_set.split(","):
        with open(os.path.join(a.data, f"compact_{name}.jsonl")) as fh:
            rows += [json.loads(line) for line in fh if line.strip()]
    stats = card_stats(rows)
    with open(a.out, "w") as fh:
        fh.write(render(stats, a))
    json.dump(stats, open(a.out.replace(".md", ".json"), "w"), indent=1)
    print(open(a.out).read())


if __name__ == "__main__":
    main()
